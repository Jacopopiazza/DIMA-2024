export const handler: Handler<GeneratorEvent> = async (event) => {
  console.log('Received event:', JSON.stringify(event));
  const { mealPlanId, preferences } = event;

  const updateMutation = `
    mutation UpdateGeneratedMealPlan($mealPlanId: ID!, $dailyPlan: DailyPlanDataInput!, $status: PlanStatus!) {
      updateGeneratedMealPlan(mealPlanId: $mealPlanId, dailyPlan: $dailyPlan, status: $status) {
        mealPlanId
        status
      }
    }
  `;

  try {
    // --- 1. Initialize Gemini Client ---
    const apiKey = await getGeminiApiKey();
    let mealPlan: DailyPlanData;
    try {
      mealPlan = await generateMealPlan(apiKey, preferences);
    } catch (error) {
      console.error('Error generating meal plan: from Gemini API: ', error);
      throw new Error('Failed to generate meal plan from Gemini API.');
    }

    // --- 3. Call AppSync with COMPLETED status ---
    await callAppSync(updateMutation, {
      mealPlanId,
      dailyPlan: mealPlan,
      status: PlanStatus.GENERATED,
    });

    console.log('Successfully processed and updated meal plan.');
    return { statusCode: 200, body: 'SUCCESS' };
  } catch (error) {
    console.error('ERROR in handler:', error);
    // --- 4. Call AppSync with FAILED status on any error ---
    try {
      const appSyncResponse = await callAppSync(updateMutation, {
        mealPlanId,
        dailyPlan: {}, // Send an empty object for the plan
        status: PlanStatus.FAILED,
      });

      console.log(
        'AppSync response:',
        JSON.stringify(appSyncResponse, null, 2),
      );
    } catch (appsyncError) {
      console.error(
        'CRITICAL ERROR: Could not even update status to FAILED:',
        appsyncError,
      );
    }

    throw error;
  }
};
