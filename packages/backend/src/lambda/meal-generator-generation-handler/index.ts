async function getGeminiApiKey(): Promise<string> {
  // ... (function remains the same as previous version)
  if (geminiApiKey) return geminiApiKey;
  if (!GEMINI_SECRET_ARN)
    throw new Error('GEMINI_SECRET_ARN environment variable not set.');

  const secret_name = 'GeminiApiSecret';

  const client = new SecretsManagerClient({
    region: AWS_REGION || `us-west-2`,
  });

  let response;

  try {
    response = await client.send(
      new GetSecretValueCommand({
        SecretId: secret_name,
        VersionStage: 'AWSCURRENT', // VersionStage defaults to AWSCURRENT if unspecified
      }),
    );
  } catch (error) {
    // For a list of exceptions thrown, see
    // https://docs.aws.amazon.com/secretsmanager/latest/apireference/API_GetSecretValue.html
    throw error;
  }

  const secret = response.SecretString;
  if (!secret) {
    throw new Error(`Secret ${secret_name} not found or empty.`);
  }
  console.log('Fetched apikey secret successfully');
  const apiKey = JSON.parse(secret)[secret_name];
  if (!apiKey) {
    throw new Error(`API key not found in secret ${secret_name}.`);
  }
  geminiApiKey = apiKey;
  return geminiApiKey!;
}

function buildUserPrompt(preferences: PlanRequestPreferencesInput): string {
  const prefsStr = Object.entries(preferences)
    .filter(([, value]) => value != null)
    .map(([key, value]) => `\n- ${key.replace(/_/g, ' ')}: ${value}`)
    .join('\n');

  return `Generate a weekly meal plan based on the following details:\n ${prefsStr}.`;
}

async function callAppSync(query: string, variables: object): Promise<any> {
  if (!APPSYNC_ENDPOINT_URL || !AWS_REGION)
    throw new Error(
      'APPSYNC_ENDPOINT_URL and AWS_REGION environment variables must be set.',
    );
  const endpoint = new URL(APPSYNC_ENDPOINT_URL);
  const signer = new SignatureV4({
    credentials: fromNodeProviderChain(), // Use default credential provider chain
    service: 'appsync',
    region: AWS_REGION,
    sha256: Sha256,
  });
  const request = new HttpRequest({
    hostname: endpoint.hostname,
    path: endpoint.pathname,
    method: 'POST',
    headers: { 'Content-Type': 'application/json', host: endpoint.hostname },
    body: JSON.stringify({ query, variables }),
  });
  const signedRequest = await signer.sign(request);
  const response = await fetch(new Request(endpoint, signedRequest));
  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(`AppSync call failed: ${errorBody}`);
  }
  return response.json();
}

